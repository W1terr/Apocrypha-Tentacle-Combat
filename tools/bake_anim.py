"""Bakes the vanilla Apocrypha tentacle attack (meshes\\dlc02\\traps\\apotentacletrap\\animations\\play01.hkx, 4 s) into
src/AnimData.h: the local transform of all 11 bones (Base01, Bone01 - Bone10) at 30 frames per second. The DLL plays
this clip itself, so the tentacle moves exactly like the vanilla one, just with its own timing (hover, repeated strikes).

usage: python bake_anim.py
"""
from pathlib import Path

import numpy as np

import gamefiles
from hkx_sample import Animation
from skeleton import read_skeleton

ROOT = Path(__file__).resolve().parent.parent
FOLDER = r"meshes\dlc02\traps\apotentacletrap"
FPS = 30


def main():
    anim = Animation(str(gamefiles.get(FOLDER + r"\animations\play01.hkx")))
    names, parents, pose = read_skeleton(str(gamefiles.get(FOLDER + r"\characterassets\skeleton.hkx")))
    assert names == ["Base01"] + [f"Bone{i:02d}" for i in range(1, 11)], names
    assert parents == list(range(-1, 10)), parents
    frames = int(round(anim.duration * FPS)) + 1
    lines = []
    previous = [None] * len(names)
    for f in range(frames):
        local = anim.sample(f / FPS)
        cells = []
        for b in range(len(names)):
            t, q, _ = local.get(b, pose[b])
            q = np.array(q, dtype=float)
            q /= np.linalg.norm(q)
            if previous[b] is not None and np.dot(previous[b], q) < 0.0:
                q = -q  # same hemisphere as the frame before: plain nlerp between frames works
            previous[b] = q
            cells.append("{ " + ", ".join(f"{v:.5f}f" for v in (*t, *q)) + " }")
        lines.append("\t\t{ " + ", ".join(cells) + " },")
    text = f"""#pragma once

// Generated by tools/bake_anim.py from the vanilla {FOLDER}\\animations\\play01.hkx - do not edit.
// Local transform of each bone (translation x y z, rotation quaternion x y z w) at {FPS} frames per second.

namespace AnimData
{{
	inline constexpr int   kBones = {len(names)};  // Base01, Bone01 ... Bone10
	inline constexpr int   kFrames = {frames};
	inline constexpr float kFPS = {FPS}.0f;
	inline constexpr float kDuration = {anim.duration:.4f}f;

	struct Key
	{{
		float t[3];
		float q[4];
	}};

	inline constexpr Key kKeys[kFrames][kBones] = {{
{chr(10).join(lines)}
	}};
}}
"""
    out = ROOT / "src" / "AnimData.h"
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}: {frames} frames x {len(names)} bones")


if __name__ == "__main__":
    main()
